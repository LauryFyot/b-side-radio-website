begin;

create or replace function public.can_reply_to_comments()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.can_moderate_comments(auth.uid())
    and exists (select 1 from public.profiles where id = auth.uid() and is_active);
$$;

revoke all on function public.can_reply_to_comments() from public;
grant execute on function public.can_reply_to_comments() to authenticated;

create table if not exists public.comment_replies (
  id bigint generated by default as identity primary key,
  comment_id bigint not null references public.comments(id) on delete cascade,
  author_id uuid not null default auth.uid() references public.profiles(id),
  author_name text not null default '',
  body text not null check (char_length(btrim(body)) between 1 and 1000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (comment_id, author_id)
);

create or replace function public.guard_comment_reply()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null or not public.can_reply_to_comments() then
    raise exception 'Only active comment moderators can reply.';
  end if;

  if tg_op = 'INSERT' then
    new.author_id := auth.uid();
    select btrim(display_name) into new.author_name
      from public.profiles where id = auth.uid();
    if coalesce(new.author_name, '') = '' then
      raise exception 'Set a public display name in your profile before replying.';
    end if;
    new.created_at := now();
  else
    if old.author_id <> auth.uid() then
      raise exception 'You can only edit your own reply.';
    end if;
    new.id := old.id;
    new.author_id := old.author_id;
    new.comment_id := old.comment_id;
    new.author_name := old.author_name;
    new.created_at := old.created_at;
  end if;

  new.body := btrim(new.body);
  new.updated_at := now();
  return new;
end;
$$;

revoke all on function public.guard_comment_reply() from public;
drop trigger if exists comment_reply_guard on public.comment_replies;
create trigger comment_reply_guard before insert or update on public.comment_replies
for each row execute function public.guard_comment_reply();

alter table public.comment_replies enable row level security;

drop policy if exists public_read_comment_replies on public.comment_replies;
create policy public_read_comment_replies on public.comment_replies
for select to anon, authenticated
using (exists (
  select 1 from public.comments where id = comment_id and status = 'approved'
));

drop policy if exists staff_read_comment_replies on public.comment_replies;
create policy staff_read_comment_replies on public.comment_replies
for select to authenticated using (public.can_reply_to_comments());

drop policy if exists staff_insert_own_comment_reply on public.comment_replies;
create policy staff_insert_own_comment_reply on public.comment_replies
for insert to authenticated
with check (public.can_reply_to_comments() and author_id = auth.uid());

drop policy if exists staff_update_own_comment_reply on public.comment_replies;
create policy staff_update_own_comment_reply on public.comment_replies
for update to authenticated
using (public.can_reply_to_comments() and author_id = auth.uid())
with check (public.can_reply_to_comments() and author_id = auth.uid());

drop policy if exists staff_delete_own_comment_reply on public.comment_replies;
create policy staff_delete_own_comment_reply on public.comment_replies
for delete to authenticated
using (public.can_reply_to_comments() and author_id = auth.uid());

revoke all on public.comment_replies from public, anon, authenticated;
grant select (id, comment_id, author_name, body, created_at, updated_at)
  on public.comment_replies to anon;
grant select, delete on public.comment_replies to authenticated;
grant insert (comment_id, body) on public.comment_replies to authenticated;
grant update (body) on public.comment_replies to authenticated;
grant usage, select on sequence public.comment_replies_id_seq to authenticated;

notify pgrst, 'reload schema';
commit;